#!/usr/bin/env bash
# Generate ColonyOS identities, deploy the server, and create the colony and CLI executor.
source "$(dirname "$0")/lib.sh"
need colonies helm kubectl openssl

# newkey <VAR_PREFIX>: append <PREFIX>_PRVKEY and <PREFIX>_ID to the identities file.
newkey() {
	local out
	out="$(colonies security generate 2>&1)"
	echo "$1_ID=$(sed -nE 's/.*Id=([0-9a-f]{64}).*/\1/p' <<<"$out")"
	echo "$1_PRVKEY=$(sed -nE 's/.*PrvKey=([0-9a-f]{64}).*/\1/p' <<<"$out")"
}

identities() {
	if [[ -f "$IDENTITIES" ]]; then
		ok "reusing identities in $IDENTITIES"
		return
	fi
	# New keys would not match the server ID stored in an existing database.
	if helm status colonies -n colonyos >/dev/null 2>&1; then
		die "ColonyOS is deployed but $IDENTITIES is gone; run 'make down' and then 'make up'"
	fi
	info "generating ColonyOS identities"
	(
		umask 077
		{
			echo "# Generated by cop1-devstack. Private keys: keep this file to yourself."
			newkey COLONIES_SERVER
			newkey COLONIES_COLONY
			newkey COLONIES_EXECUTOR
			echo "COLONIES_DB_PASSWORD=$(openssl rand -hex 16)"
		} >"$IDENTITIES"
	)
	grep -qE '^COLONIES_EXECUTOR_PRVKEY=[0-9a-f]{64}$' "$IDENTITIES" || die "key generation failed; see $IDENTITIES"
}

server() {
	load_identities
	local values="$STATE/colonies-values.yaml"
	(
		umask 077
		cat >"$values" <<-YAML
			image: colonyos/colonies:$COLONIES_VERSION
			serverPrvKey: "$COLONIES_SERVER_PRVKEY"
			serverId: "$COLONIES_SERVER_ID"
			dbPassword: "$COLONIES_DB_PASSWORD"
			nodePort: $COLONIES_NODEPORT
			db:
			  image: $TIMESCALEDB_IMAGE
		YAML
	)
	info "deploying ColonyOS $COLONIES_VERSION"
	helm upgrade --install colonies "$ROOT/charts/colonies" \
		--namespace colonyos --create-namespace \
		--values "$values" --wait --timeout 5m >/dev/null
	colonies_cli_env
	retry 120 "ColonyOS API on localhost:$COLONIES_HOST_PORT" colonies_alive
	ok "ColonyOS server up on localhost:$COLONIES_HOST_PORT"
}

colony() {
	colonies_cli_env
	if colonies colony ls 2>/dev/null | grep -qw "$COLONY_NAME"; then
		ok "colony $COLONY_NAME exists"
	else
		info "creating colony $COLONY_NAME"
		quiet colonies colony add --name "$COLONY_NAME" --colonyid "$COLONIES_COLONY_ID"
	fi

	# One executor identity shared by the CLI and Kolony (Blueprints and ColonyProcesses).
	# Look it up by exact name: grepping "executor ls" also matches docker-reconciler-devstack.
	if colonies executor get --name devstack >/dev/null 2>&1; then
		ok "executor devstack exists"
	else
		info "registering executor devstack"
		quiet colonies executor add --name devstack --type cli --executorid "$COLONIES_EXECUTOR_ID" --approve
	fi
}

# Writes the CLI env file users source to talk to the colony.
envfile() {
	colonies_cli_env
	(
		umask 077
		cat >"$STATE/colonies.env" <<-EOF2
			# source .devstack/colonies.env to use the colonies CLI against the devstack
			export PATH="$BIN:\$PATH"
			export COLONIES_SERVER_HOST=localhost COLONIES_SERVER_PORT=$COLONIES_HOST_PORT
			export COLONIES_TLS=false COLONIES_INSECURE=true
			export COLONIES_COLONY_NAME=$COLONY_NAME
			export COLONIES_COLONY_ID=$COLONIES_COLONY_ID
			export COLONIES_COLONY_PRVKEY=$COLONIES_COLONY_PRVKEY
			export COLONIES_PRVKEY=$COLONIES_EXECUTOR_PRVKEY
			export KUBECONFIG="$KUBECONFIG"
		EOF2
	)
	ok "CLI environment: source .devstack/colonies.env"
}

# Steps run one per line: "a && b" would disable set -e inside them.
case "${1:-up}" in
up)
	identities
	server
	colony
	envfile
	;;
*) "$1" ;;
esac
